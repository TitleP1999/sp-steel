function localize(source: string, locale: Locale) {
  if (locale === "th") return source;
  const dictionary = translations[locale];
  const trimmed = source.trim();
  const exact = dictionary[trimmed];
  if (exact !== undefined) return source.replace(trimmed, exact);

  let result = source;
  for (const [thai, translated] of Object.entries(dictionary).sort((a, b) => b[0].length - a[0].length)) {
    if (thai.length < 2 || !result.includes(thai)) continue;
    result = result.split(thai).join(translated);
  }
  return result;
}

export function translateContent(source: string, locale: Locale) {
  return localize(source, locale);
}

function translateTextNode(node: Text, locale: Locale) {
  const current = node.nodeValue ?? "";
  let record = textOriginals.get(node);
  if (!record) {
    record = { source: current, rendered: current };
    textOriginals.set(node, record);
  } else if (current !== record.rendered) {
    record = { source: current, rendered: current };
    textOriginals.set(node, record);
  }
  const next = localize(record.source, locale);
  if (current !== next) {
    record.rendered = next;
    node.nodeValue = next;
  }
}

function translateAttribute(element: Element, attribute: string, locale: Locale) {
  const current = element.getAttribute(attribute);
  if (current === null) return;
  let attributes = attributeOriginals.get(element);
  if (!attributes) { attributes = new Map(); attributeOriginals.set(element, attributes); }
  let record = attributes.get(attribute);
  if (!record) { record = { source: current, rendered: current }; attributes.set(attribute, record); }
  else if (current !== record.rendered) { record = { source: current, rendered: current }; attributes.set(attribute, record); }
  const next = localize(record.source, locale);
  if (next !== current) { record.rendered = next; element.setAttribute(attribute, next); }
}

function translateElementTree(root: Node, locale: Locale) {
  const excluded = "SCRIPT,STYLE,NOSCRIPT,OPTION[data-no-translate], [data-no-translate]";
  const elementRoot = root instanceof Element ? root : root.parentElement;
  if (elementRoot?.closest(excluded)) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest(excluded)) continue;
    translateTextNode(node as Text, locale);
  }
  const elements = root instanceof Element ? [root, ...Array.from(root.querySelectorAll("[aria-label],[placeholder],[title],[alt]"))] : [];
  for (const element of elements) {
    if (element.closest(excluded)) continue;
    for (const attribute of ["aria-label", "placeholder", "title", "alt"]) translateAttribute(element, attribute, locale);
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("th");
  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh" || stored === "th") setLocaleState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : locale === "en" ? "en" : "th";
    translateElementTree(document.body, locale);
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === "characterData" && record.target instanceof Text) translateTextNode(record.target, locale);
        if (record.type === "attributes" && record.target instanceof Element && record.attributeName) translateAttribute(record.target, record.attributeName, locale);
        for (const added of Array.from(record.addedNodes)) translateElementTree(added, locale);
      }
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "placeholder", "title", "alt"] });
    return () => observer.disconnect();
  }, [locale]);

  const value = useMemo<LanguageContextValue>(() => ({
    locale,
    setLocale: next => { window.localStorage.setItem(STORAGE_KEY, next); setLocaleState(next); },
  }), [locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() { return useContext(LanguageContext); }

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale } = useLanguage();
  const [open, setOpen] = useState(false);
  const container = useRef<HTMLDivElement>(null);
  const languages: { value: Locale; flag: string; label: string }[] = [
    { value: "th", flag: "/flags/th.svg", label: "ไทย" },
    { value: "en", flag: "/flags/gb.svg", label: "English" },
    { value: "zh", flag: "/flags/cn.svg", label: "中文" },
  ];
  const current = languages.find(language => language.value === locale) ?? languages[0];

  useEffect(() => {
    if (!open) return;
    const close = (event: PointerEvent) => {
      if (!container.current?.contains(event.target as Node)) setOpen(false);
    };
    const escape = (event: KeyboardEvent) => {
      if (event.key === "Escape") setOpen(false);
    };
    document.addEventListener("pointerdown", close);
    document.addEventListener("keydown", escape);
    return () => {
      document.removeEventListener("pointerdown", close);
      document.removeEventListener("keydown", escape);
    };
  }, [open]);

  return <div ref={container} data-no-translate className="relative shrink-0">
    <button type="button" onClick={() => setOpen(value => !value)} aria-label={`Language: ${current.label}`} aria-haspopup="menu" aria-expanded={open} className={`inline-flex items-center justify-center gap-1 rounded-full border border-white/30 bg-white/10 text-white outline-none transition hover:bg-white/20 focus:ring-2 focus:ring-white/70 ${compact ? "h-8 min-w-11 px-2" : "h-10 min-w-12 px-2.5"}`}>
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={current.flag} alt="" className={`rounded-[2px] object-cover shadow-sm ${compact ? "h-4 w-6" : "h-[18px] w-7"}`} />
      <span aria-hidden="true" className={`transition-transform ${open ? "rotate-180" : ""}`}>⌄</span>
    </button>
    {open && <div role="menu" aria-label="Language / ภาษา / 语言" className="absolute right-0 top-full z-[120] mt-2 min-w-36 overflow-hidden rounded-xl border border-zinc-200 bg-white py-1 text-sm font-bold tracking-normal text-[#202124] shadow-xl">
      {languages.map(language => <button key={language.value} type="button" role="menuitemradio" aria-checked={locale === language.value} onClick={() => { setLocale(language.value); setOpen(false); }} className={`flex w-full items-center gap-3 px-4 py-2.5 text-left transition hover:bg-zinc-100 ${locale === language.value ? "bg-zinc-100 text-[#8b352d]" : ""}`}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={language.flag} alt="" className="h-4 w-6 rounded-[2px] object-cover shadow-sm" />
        <span>{language.label}</span>
      </button>)}
    </div>}
  </div>;
}
